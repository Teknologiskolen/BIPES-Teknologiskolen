(function () {
  if (!window.Blockly || !Blockly.Input || !Blockly.Input.prototype ||
      !Blockly.Input.prototype.appendField || Blockly.Input.prototype.__bipesI18n)
    return;

  function currentLanguage() {
    var lang = (window.bipes && window.bipes.lang) ||
      (document.documentElement && document.documentElement.lang) || 'en';
    return String(lang).toLowerCase().split(/[-_]/)[0];
  }

  function normalizeCaption(text) {
    if (typeof text !== 'string')
      return text;
    text = text.trim();
    return text.replace(/[A-Za-zÆØÅÄÖÜæøåäöü]/u, function (letter) {
      return letter.toLocaleUpperCase(currentLanguage());
    });
  }

  function translate(text) {
    if (typeof text !== 'string' || !text)
      return text;
    var trimmed = text.trim();
    var dictionary = window.BIPES_BLOCK_I18N || {};
    var entry = dictionary[trimmed] || dictionary[text];
    return normalizeCaption(
      entry && entry[currentLanguage()] ? entry[currentLanguage()] : trimmed
    );
  }

  // Serialized label fields can be assigned again while toolbox XML or an old
  // project is loaded. Normalize those updates too, otherwise saved English
  // captions can overwrite the translated value created during block init.
  [Blockly.FieldLabel, Blockly.FieldLabelSerializable].forEach(function (ctor) {
    if (!ctor || !ctor.prototype ||
        !Object.prototype.hasOwnProperty.call(ctor.prototype, 'setValue') ||
        ctor.prototype.__bipesI18n)
      return;
    var setValue = ctor.prototype.setValue;
    ctor.prototype.setValue = function (value) {
      return setValue.call(this, translate(value));
    };
    ctor.prototype.__bipesI18n = true;
  });

  var orig = Blockly.Input.prototype.appendField;
  Blockly.Input.prototype.appendField = function (field, opt_name) {
    if (typeof field === 'string') {
      field = translate(field);
    } else if (field && typeof field.getValue === 'function' &&
               typeof field.setValue === 'function' &&
               ((Blockly.FieldLabel && field instanceof Blockly.FieldLabel) ||
                (Blockly.FieldLabelSerializable &&
                 field instanceof Blockly.FieldLabelSerializable))) {
      field.setValue(translate(field.getValue()));
    }
    return orig.call(this, field, opt_name);
  };
  Blockly.Input.prototype.__bipesI18n = true;

  // Dropdown captions are not passed to appendField as strings. Translate the
  // displayed caption while preserving the stable value used by generators and
  // saved projects. This also covers dynamically generated dropdown options.
  if (Blockly.FieldDropdown && Blockly.FieldDropdown.prototype &&
      Blockly.FieldDropdown.prototype.getOptions &&
      !Blockly.FieldDropdown.prototype.__bipesI18n) {
    var getOptions = Blockly.FieldDropdown.prototype.getOptions;
    Blockly.FieldDropdown.prototype.getOptions = function (useCache) {
      var options = getOptions.call(this, useCache);
      return options.map(function (option) {
        if (!option || option.length < 2 || typeof option[0] !== 'string')
          return option;
        return [translate(option[0]), option[1]];
      });
    };
    Blockly.FieldDropdown.prototype.__bipesI18n = true;
  }
})();
